document.addEventListener('DOMContentLoaded', () => {
  initNavbar();
  initModal();
  updateLanguageUI();
});

/* Toggle Language Function */
window.toggleLanguage = function() {
  currentLang = currentLang === 'ar' ? 'en' : 'ar';
  const html = document.documentElement;
  
  if (currentLang === 'ar') {
    html.setAttribute('dir', 'rtl');
    html.setAttribute('lang', 'ar');
  } else {
    html.setAttribute('dir', 'ltr');
    html.setAttribute('lang', 'en');
  }

  updateLanguageUI();
};

/* Update UI Text Nodes & Direction */
function updateLanguageUI() {
  const dictionary = i18n[currentLang];
  const elements = document.querySelectorAll('[data-i18n]');

  elements.forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dictionary[key]) {
      el.innerHTML = dictionary[key];
    }
  });

  // Update button label
  const langBtn = document.getElementById('langToggleBtn');
  if (langBtn) langBtn.innerText = dictionary.lang_btn;

  // Update placeholders
  const inputName = document.getElementById('inputName');
  const inputPhone = document.getElementById('inputPhone');

  if (inputName) inputName.setAttribute('placeholder', dictionary.ph_name);
  if (inputPhone) inputPhone.setAttribute('placeholder', dictionary.ph_phone);
}

/* 1. Navbar Scroll Effect */
function initNavbar() {
  const navbar = document.getElementById('navbar');
  window.addEventListener('scroll', () => {
    if (window.scrollY > 40) {
      navbar.classList.add('scrolled');
    } else {
      navbar.classList.remove('scrolled');
    }
  });
}

/* 2. Strategy Consultation Modal Form Handler */
function initModal() {
  const overlay = document.getElementById('modalOverlay');
  const form = document.getElementById('bookingForm');

  window.openModal = function() {
    overlay.classList.add('active');
  };

  window.closeModal = function() {
    overlay.classList.remove('active');
  };

  overlay.addEventListener('click', (e) => {
    if (e.target === overlay) {
      closeModal();
    }
  });

  form.addEventListener('submit', (e) => {
    e.preventDefault();
    const msg = currentLang === 'ar' 
      ? 'شكراً لك! تم استلام طلبك بوكالة OTB Agency (+20 10 08080295). سيتواصل معك أحد متخصصي الفريق فوراً.'
      : 'Thank you! Your request has been received by OTB Agency (+20 10 08080295). Our team will get back to you shortly.';
    alert(msg);
    closeModal();
    form.reset();
  });
}
